// Codex hooks are installed as managed hooks in Codex's system requirements
// file, not per worktree. Codex only runs a project or user hook after a
// human has trusted its hash, but managed hooks are trusted by policy, and a
// root-owned requirements file cannot be edited by the agent it guards.
//
// The requirements file holds one dispatcher hook per event, which calls
// `gt hooks codex run <event>`. The dispatcher computes the same hook set a
// Claude agent in that role gets (ComputeExpected: base, role and rig
// overrides) and runs it, translating between the Codex and Claude hook
// payloads. Adding or changing a guard therefore needs a gt update, not a
// new requirements file.

// CodexRequirementsPath is where Codex reads system requirements on macOS
// and Linux.
const CodexRequirementsPath = "/etc/codex/requirements.toml"

// CodexEvents are the Codex hook events the dispatcher handles, in the order
// the requirements file lists them.
var CodexEvents = []string{"SessionStart", "UserPromptSubmit", "PreToolUse", "PostToolUse", "PreCompact", "Stop"}

// codexEventTimeouts bound each dispatcher run, in seconds. Most events run
// a few short guards; SessionStart and UserPromptSubmit read the Dolt-backed
// inbox and the role context, which can be slow under load.
var codexEventTimeouts = map[string]int{
	"SessionStart":     180,
	"UserPromptSubmit": 90,
	"PreToolUse":       60,
	"PostToolUse":      60,
	"PreCompact":       180,
	"Stop":             60,
}

// codexContextEvents are the events whose stdout Codex adds to the model's
// context. Codex spills hook context over ~2,500 tokens to a file unless
// additionalContextLimit is 0, and gt prime output is larger than that.
var codexContextEvents = map[string]bool{"SessionStart": true, "UserPromptSubmit": true}

// CodexDispatchCommand is the requirements-file command for one event.
func CodexDispatchCommand(gtBin, event string) string {
	return shellQuote(gtBin) + " hooks codex run " + event
}

// CodexRequirementsTOML renders the requirements file that installs the
// dispatcher for every event. Other hook sources are switched off, hooks is
// pinned on so a session cannot turn the managed hooks off, and memories is
// pinned off: Codex's own memory files
// would let a policy persist outside the formula, beads and mail, the same
// drift the memory-write guard blocks for Claude.
func CodexRequirementsTOML(gtBin string) string {
	var b strings.Builder
	b.WriteString("# Gas Town managed Codex hooks. Generated by `gt hooks codex requirements`.\n")
	b.WriteString("# Install as root: gt hooks codex requirements | sudo tee " + CodexRequirementsPath + "\n")
	b.WriteString("# Each hook calls the gt dispatcher, which runs the role's Gas Town hooks.\n\n")
	// Only these managed hooks run: no user, project, session or plugin
	// hooks, so a Codex agent never stops at a hook-review dialog and cannot
	// add hooks of its own.
	b.WriteString("allow_managed_hooks_only = true\n\n")
	b.WriteString("[features]\nhooks = true\nmemories = false\n")
	for _, event := range CodexEvents {
		fmt.Fprintf(&b, "\n[[hooks.%s]]\n\n[[hooks.%s.hooks]]\n", event, event)
		b.WriteString("type = \"command\"\n")
		fmt.Fprintf(&b, "command = %q\n", CodexDispatchCommand(gtBin, event))
		fmt.Fprintf(&b, "timeout = %d\n", codexEventTimeouts[event])
		if codexContextEvents[event] {
			b.WriteString("additionalContextLimit = 0\n")
		}
	}
	return b.String()
}

// CheckCodexRequirements reports what is missing from a requirements file for
// the dispatcher to run every event with gtBin. A nil error means the file
// allows managed hooks only, pins hooks on, pins memories off, and has an
// unfiltered dispatcher hook for each event.
func CheckCodexRequirements(data []byte, gtBin string) error {
	var req struct {
		AllowManagedHooksOnly bool                      `toml:"allow_managed_hooks_only"`
		Features              map[string]bool           `toml:"features"`
		Hooks                 map[string]toml.Primitive `toml:"hooks"`
	}
	md, err := toml.Decode(string(data), &req)
	if err != nil {
		return fmt.Errorf("parsing requirements: %w", err)
	}
	var problems []string
	if !req.AllowManagedHooksOnly {
		problems = append(problems, "allow_managed_hooks_only = true is missing")
	}
	if !req.Features["hooks"] {
		problems = append(problems, "[features] hooks = true is missing")
	}
	if v, ok := req.Features["memories"]; !ok || v {
		problems = append(problems, "[features] memories = false is missing")
	}
	for _, event := range CodexEvents {
		var groups []struct {
			Matcher *string `toml:"matcher"`
			Hooks   []struct {
				Type    string `toml:"type"`
				Command string `toml:"command"`
			} `toml:"hooks"`
		}
		if prim, ok := req.Hooks[event]; ok {
			if err := md.PrimitiveDecode(prim, &groups); err != nil {
				return fmt.Errorf("parsing hooks.%s: %w", event, err)
			}
		}
		want := CodexDispatchCommand(gtBin, event)
		found := false
		for _, g := range groups {
			if g.Matcher != nil && *g.Matcher != "" && *g.Matcher != "*" {
				continue
			}
			for _, h := range g.Hooks {
				if h.Type == "command" && h.Command == want {
					found = true
				}
			}
		}
		if !found {
			problems = append(problems, fmt.Sprintf("hooks.%s does not run %q", event, want))
		}
	}
	if len(problems) > 0 {
		return fmt.Errorf("%s", strings.Join(problems, "; "))
	}
	return nil
}

// VerifyCodexManagedHooks checks the system requirements file for the
// current gt binary. Agent startup calls it so a Codex agent never runs
// without its guards.
func VerifyCodexManagedHooks() error {
	return verifyCodexManagedHooksAt(CodexRequirementsPath, resolveGTBinary())
}

func verifyCodexManagedHooksAt(path, gtBin string) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("Codex managed hooks are not installed (%w); install them with: gt hooks codex requirements | sudo tee %s", err, path)
	}
	if err := CheckCodexRequirements(data, gtBin); err != nil {
		return fmt.Errorf("Codex managed hooks in %s are out of date (%w); reinstall with: gt hooks codex requirements | sudo tee %s", path, err, path)
	}
	return nil
}

// GTBinary is the gt path hook commands use: the running binary.
func GTBinary() string {
	return resolveGTBinary()
}

// TargetForRole maps a session's GT_ROLE to its hooks override target, the
// same keys DiscoverTargets gives Claude settings files.
func TargetForRole(gtRole string) string {
	if gtRole == "deacon/boot" {
		return "boot"
	}
	parts := strings.Split(gtRole, "/")
	if len(parts) == 3 && (parts[1] == "polecats" || parts[1] == "crew") {
		return parts[0] + "/" + parts[1]
	}
	return gtRole
}

// CodexHookRunner runs one Gas Town hook command with the given stdin and
// returns its stdout, stderr and exit code.
type CodexHookRunner func(command string, stdin []byte, timeout time.Duration) (stdout, stderr []byte, exitCode int)

// CodexDispatchResult is what the dispatcher hands back to Codex.
type CodexDispatchResult struct {
	Stdout   []byte
	Stderr   []byte
	ExitCode int
}

// codexPayload holds the fields of a Codex hook payload the dispatcher reads.
// The rest of the payload passes through to the Gas Town hooks unchanged.
type codexPayload struct {
	ToolName  string          `json:"tool_name"`
	ToolInput json.RawMessage `json:"tool_input"`
	Cwd       string          `json:"cwd"`
	Source    string          `json:"source"`
	Trigger   string          `json:"trigger"`
}

// codexCandidate is one Claude-shaped view of a Codex event: the value the
// Claude matcher is tested against, the Bash command (for Bash(...) matchers)
// and the payload the hook receives.
type codexCandidate struct {
	value   string
	command string
	payload []byte
}

// DispatchCodex runs the hooks in cfg that match a Codex event and combines
// their results the way Codex expects:
//   - a hook exiting 2 blocks; its stderr is the reason and no later hook runs
//   - other non-zero exits are reported on stderr and do not block
//   - stdout reaches Codex only for SessionStart and UserPromptSubmit (added
//     to context) and, when it is a JSON object, for Stop and PostToolUse
func DispatchCodex(event string, payload []byte, cfg *HooksConfig, run CodexHookRunner) CodexDispatchResult {
	var p codexPayload
	if err := json.Unmarshal(payload, &p); err != nil {
		return CodexDispatchResult{Stderr: []byte(fmt.Sprintf("gt hooks codex: unreadable %s payload: %v\n", event, err))}
	}

	var res CodexDispatchResult
	for _, c := range codexCandidates(event, p, payload) {
		ran := map[string]bool{}
		for _, entry := range cfg.GetEntries(event) {
			if !claudeMatcherMatches(entry.Matcher, c.value, c.command) {
				continue
			}
			for _, h := range entry.Hooks {
				if h.Type != "command" || h.Command == "" || ran[h.Command] {
					continue
				}
				ran[h.Command] = true
				timeout := 60 * time.Second
				if h.Timeout > 0 {
					timeout = time.Duration(h.Timeout) * time.Second
				}
				stdout, stderr, code := run(h.Command, c.payload, timeout)
				if code == 2 && len(strings.TrimSpace(string(stderr))) == 0 {
					// Codex ignores an exit-2 block with an empty stderr
					// reason. The inline guards echo their reason to
					// stdout, which Claude accepts.
					stderr = stdout
					if len(strings.TrimSpace(string(stderr))) == 0 {
						stderr = []byte(fmt.Sprintf("blocked by Gas Town hook %q\n", h.Command))
					}
				}
				res.Stderr = append(res.Stderr, stderr...)
				if code == 2 {
					res.ExitCode = 2
					return res
				}
				if code != 0 {
					res.Stderr = append(res.Stderr, fmt.Sprintf("gt hooks codex: %q exited %d\n", h.Command, code)...)
				}
				res.Stdout = appendCodexStdout(event, res.Stdout, stdout)
			}
		}
	}
	return res
}

// appendCodexStdout keeps the stdout Codex can use for the event. Codex adds
// plain text to context for SessionStart and UserPromptSubmit; Stop and
// PostToolUse accept only a JSON object, and Codex ignores PreCompact stdout.
func appendCodexStdout(event string, acc, out []byte) []byte {
	if len(strings.TrimSpace(string(out))) == 0 {
		return acc
	}
	switch event {
	case "SessionStart", "UserPromptSubmit":
		if len(acc) > 0 && acc[len(acc)-1] != '\n' {
			acc = append(acc, '\n')
		}
		return append(acc, out...)
	case "Stop", "PostToolUse":
		var obj map[string]any
		if len(acc) == 0 && json.Unmarshal(out, &obj) == nil {
			return out
		}
	}
	return acc
}

// codexCandidates translates a Codex event into the Claude tool names and
// payloads the Gas Town hooks were written for.
func codexCandidates(event string, p codexPayload, payload []byte) []codexCandidate {
	switch event {
	case "PreToolUse", "PostToolUse":
	case "SessionStart":
		return []codexCandidate{{value: p.Source, payload: payload}}
	case "PreCompact":
		return []codexCandidate{{value: p.Trigger, payload: payload}}
	default:
		return []codexCandidate{{payload: payload}}
	}

	var input struct {
		Command string `json:"command"`
	}
	_ = json.Unmarshal(p.ToolInput, &input)

	switch p.ToolName {
	case "Bash":
		return []codexCandidate{{value: "Bash", command: input.Command, payload: payload}}
	case "apply_patch":
		// Claude's file guards read tool_input.file_path, so each file the
		// patch touches becomes an Edit call on that file.
		paths := applyPatchPaths(input.Command, p.Cwd)
		if len(paths) == 0 {
			return []codexCandidate{{value: "Edit", payload: rewriteToolCall(payload, "Edit", nil)}}
		}
		var out []codexCandidate
		for _, path := range paths {
			out = append(out, codexCandidate{value: "Edit", payload: rewriteToolCall(payload, "Edit", map[string]any{"file_path": path, "command": input.Command})})
		}
		return out
	case "request_user_input":
		return []codexCandidate{{value: "AskUserQuestion", payload: rewriteToolCall(payload, "AskUserQuestion", nil)}}
	default:
		// MCP tools use the same mcp__server__tool names in both clients.
		return []codexCandidate{{value: p.ToolName, payload: payload}}
	}
}

// rewriteToolCall returns payload with tool_name replaced and, when toolInput
// is non-nil, tool_input replaced.
func rewriteToolCall(payload []byte, toolName string, toolInput map[string]any) []byte {
	var m map[string]any
	if err := json.Unmarshal(payload, &m); err != nil {
		return payload
	}
	m["tool_name"] = toolName
	if toolInput != nil {
		m["tool_input"] = toolInput
	}
	out, err := json.Marshal(m)
	if err != nil {
		return payload
	}
	return out
}

var applyPatchHeader = regexp.MustCompile(`(?m)^\*\*\* (?:Add File|Update File|Delete File|Move to): (.+?)\s*$`)

// applyPatchPaths returns the files an apply_patch body creates, changes,
// deletes or renames to, resolved against cwd.
func applyPatchPaths(patch, cwd string) []string {
	var paths []string
	for _, m := range applyPatchHeader.FindAllStringSubmatch(patch, -1) {
		path := m[1]
		if !filepath.IsAbs(path) && cwd != "" {
			path = filepath.Join(cwd, path)
		}
		paths = append(paths, path)
	}
	return paths
}

var (
	toolPatternMatcher = regexp.MustCompile(`^([A-Za-z0-9_|]+)\((.*)\)$`)
	shellSeparators    = regexp.MustCompile(`&&|\|\||[;|\n]`)
)

// claudeMatcherMatches reports whether a Claude hook matcher selects value.
// An empty matcher or "*" matches everything. "Tool(pattern)" matches when
// the tool name matches and the Bash command, or any of its subcommands split
// at shell separators, matches the glob pattern ("*" is any text). Any other
// matcher is a regular expression over the whole value, so "Write|Edit"
// matches "Edit".
func claudeMatcherMatches(matcher, value, command string) bool {
	if matcher == "" || matcher == "*" {
		return true
	}
	if m := toolPatternMatcher.FindStringSubmatch(matcher); m != nil {
		if !matchesWhole(m[1], value) {
			return false
		}
		glob := globRegexp(m[2])
		if glob.MatchString(strings.TrimSpace(command)) {
			return true
		}
		for _, sub := range shellSeparators.Split(command, -1) {
			if glob.MatchString(strings.TrimSpace(sub)) {
				return true
			}
		}
		return false
	}
	return matchesWhole(matcher, value)
}

func matchesWhole(pattern, value string) bool {
	re, err := regexp.Compile("^(?:" + pattern + ")$")
	if err != nil {
		return pattern == value
	}
	return re.MatchString(value)
}

func globRegexp(glob string) *regexp.Regexp {
	parts := strings.Split(glob, "*")
	for i, part := range parts {
		parts[i] = regexp.QuoteMeta(part)
	}
	return regexp.MustCompile("(?s)^" + strings.Join(parts, ".*") + "$")
}

// RunCodexHookCommand runs a hook command through /bin/sh, as Claude Code
// does. Output goes to temporary files rather than pipes: a hook that
// backgrounds work (`gt costs record &`) keeps the output open after the
// shell exits, and waiting on a pipe would hold Codex until it finishes.
func RunCodexHookCommand(command string, stdin []byte, timeout time.Duration) ([]byte, []byte, int) {
	stdoutFile, err := os.CreateTemp("", "gt-codex-hook-out-*")
	if err != nil {
		return nil, []byte(fmt.Sprintf("gt hooks codex: %v\n", err)), 1
	}
	defer os.Remove(stdoutFile.Name())
	defer stdoutFile.Close()
	stderrFile, err := os.CreateTemp("", "gt-codex-hook-err-*")
	if err != nil {
		return nil, []byte(fmt.Sprintf("gt hooks codex: %v\n", err)), 1
	}
	defer os.Remove(stderrFile.Name())
	defer stderrFile.Close()

	cmd := exec.Command("/bin/sh", "-c", command)
	cmd.Stdin = strings.NewReader(string(stdin))
	cmd.Stdout = stdoutFile
	cmd.Stderr = stderrFile
	if err := cmd.Start(); err != nil {
		return nil, []byte(fmt.Sprintf("gt hooks codex: starting %q: %v\n", command, err)), 1
	}
	done := make(chan error, 1)
	go func() { done <- cmd.Wait() }()
	code := 0
	select {
	case err := <-done:
		if exitErr, ok := err.(*exec.ExitError); ok {
			code = exitErr.ExitCode()
		} else if err != nil {
			code = 1
		}
	case <-time.After(timeout):
		_ = cmd.Process.Kill()
		<-done
		fmt.Fprintf(stderrFile, "gt hooks codex: %q timed out after %s\n", command, timeout)
		code = 1
	}
	stdout, _ := os.ReadFile(stdoutFile.Name())
	stderr, _ := os.ReadFile(stderrFile.Name())
	return stdout, stderr, code
}

func shellQuote(s string) string {
	if s != "" && !strings.ContainsAny(s, " \t\n'\"\\$`;&|<>()*?[]#~") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
