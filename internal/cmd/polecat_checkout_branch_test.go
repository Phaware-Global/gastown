// TestBeadIDPattern pins the regex used by `gt polecat checkout-branch` to
// validate the bead-id arg before constructing the branch name. The pattern
// has to accept the standard bd issue forms (gt-mwy, gt-mwy.5, hq-1pl,
// gt-i71) without admitting shell-injection-friendly characters that would
// then leak into the branch name.
func TestBeadIDPattern(t *testing.T) {
	cases := []struct {
		in   string
		want bool
	}{
		// Positives — every shape we see in practice.
		{"gt-mwy", true},
		{"gt-mwy.5", true},
		{"gt-i71", true},
		{"hq-1pl", true},
		{"hq-wisp-ku6", true},
		{"gt-1qlg", true},
		// Rig prefixes are not limited to 2-3 chars.
		{"hmetet-za9w", true},
		{"hga-x0sc", true},
		{"abcd-mwy", true},
		{"a1b2-mwy.3", true},
		{"a-mwy", true},                    // 1-char prefix (deriveBeadsPrefix keeps names of 3 chars or fewer)
		{"x-ab1", true},                    // 1-char prefix
		{"heartworksmobileapp-za9w", true}, // 19-char prefix, one under the cap
		{"abcdefghijklmnopqrst-x", true},   // 20-char prefix, the beadsPrefixRegexp maximum
		// Subtask depth more than one level (gt-mwy.5.2) is occasionally
		// generated by mayor when fanning out work; the pattern must accept
		// chained .N suffixes without degenerating to "anything goes".
		{"gt-mwy.5.2", true},

		// Negatives — guard against shell-injection / branch-name pollution.
		{"", false},
		{"gt", false},                      // no suffix
		{"gt-", false},                     // empty suffix
		{"GT-MWY", false},                  // uppercase prefix
		{"gt-MWY", false},                  // uppercase body
		{"gt mwy", false},                  // space
		{"gt-mwy/something", false},        // slash
		{"gt-mwy;rm -rf /", false},         // shell metacharacter
		{"gt-mwy`whoami`", false},          // backticks
		{"gt-mwy$(whoami)", false},         // command substitution
		{"1ab-mwy", false},                 // prefix must start with a letter
		{"abcdefghijklmnopqrstu-x", false}, // 21-char prefix exceeds the cap
		{"../x", false},                    // path-like
		{"a b", false},                     // whitespace
		{"-gt-mwy", false},                 // empty prefix
		{"--gt-mwy", false},                // leading dashes
	}
	for _, c := range cases {
		t.Run(c.in, func(t *testing.T) {
			got := beadIDPattern.MatchString(c.in)
			if got != c.want {
				t.Errorf("beadIDPattern.MatchString(%q) = %v; want %v", c.in, got, c.want)
			}
		})
	}
}

// validateBeadID layers git-ref-rule checks on top of the regex. The
// pattern alone admits some refs git would reject — `..` in a ref name,
// trailing `.`, and `.lock` suffixes — so callers seeing a stricter regex
// might still hit confusing failures at the `git checkout -b` step. This
// test pins the additional rejections so future regex relaxation can't
// silently regress git-ref safety. Iter-2 review on PR #49 flagged the
// gap.
func TestValidateBeadID_RejectsGitRefRuleViolations(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want string // expected substring of the error message
	}{
		{"double dot rejected", "gt-mwy..5", `".."`},
		{"trailing dot rejected", "gt-mwy.", `"."`},
		{"lock suffix rejected", "gt-mwy.lock", `".lock"`},
		{"chained .lock rejected", "gt-wisp-ku6.lock", `".lock"`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			err := validateBeadID(c.in)
			if err == nil {
				t.Fatalf("validateBeadID(%q) = nil; want error mentioning %q", c.in, c.want)
			}
			if !strings.Contains(err.Error(), c.want) {
				t.Errorf("validateBeadID(%q) error %q; want to contain %q", c.in, err.Error(), c.want)
			}
		})
	}
}

// Positive cases for validateBeadID: anything that passes the regex AND
// the additional ref-rule checks must validate. Mostly redundant with
// TestBeadIDPattern's positives, but proves the layered checks compose
// correctly — they don't accidentally reject legitimate IDs.
func TestValidateBeadID_AcceptsLegitimateIDs(t *testing.T) {
	for _, id := range []string{
		"gt-mwy",
		"gt-mwy.5",
		"gt-mwy.5.2",
		"hq-wisp-ku6",
		"gt-i71",
	} {
		t.Run(id, func(t *testing.T) {
			if err := validateBeadID(id); err != nil {
				t.Errorf("validateBeadID(%q) = %v; want nil", id, err)
			}
		})
	}
}

// newRigClone builds a town with one rig whose polecat worktree is a clone of
// an origin that has main (the remote HEAD), develop, and feature/stack, each
// at a distinct commit. A non-empty rigDefault is written to the rig's
// config.json as default_branch. It returns the worktree path and the commit
// each branch points at.
func newRigClone(t *testing.T, rigDefault string) (clone string, tips map[string]string) {
	t.Helper()
	town := t.TempDir()
	rigDir := filepath.Join(town, "alpha")
	if err := os.MkdirAll(filepath.Join(town, "mayor"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(town, "mayor", "town.json"), []byte("{}"), 0o644); err != nil { //nolint:gosec // G306: test fixture
		t.Fatal(err)
	}
	clone = filepath.Join(rigDir, "polecats", "nux", "alpha")
	if err := os.MkdirAll(filepath.Dir(clone), 0o755); err != nil {
		t.Fatal(err)
	}
	if rigDefault != "" {
		cfg := fmt.Sprintf(`{"default_branch":%q}`, rigDefault)
		if err := os.WriteFile(filepath.Join(rigDir, "config.json"), []byte(cfg), 0o644); err != nil { //nolint:gosec // G306: test fixture
			t.Fatal(err)
		}
	}

	root := t.TempDir()
	origin := filepath.Join(root, "origin.git")
	seed := filepath.Join(root, "seed")
	gitRun(t, root, "init", "--bare", "-b", "main", origin)
	gitRun(t, root, "init", "-b", "main", seed)
	gitRun(t, seed, "config", "user.email", "test@example.com")
	gitRun(t, seed, "config", "user.name", "Test")
	gitRun(t, seed, "remote", "add", "origin", origin)

	tips = map[string]string{}
	for _, branch := range []string{"main", "develop", "feature/stack"} {
		if branch != "main" {
			gitRun(t, seed, "checkout", "-q", "-b", branch, "main")
		}
		gitRun(t, seed, "commit", "--allow-empty", "-m", "tip of "+branch)
		gitRun(t, seed, "push", "-q", "origin", branch)
		out, err := exec.Command("git", "-C", seed, "rev-parse", "HEAD").Output()
		if err != nil {
			t.Fatal(err)
		}
		tips[branch] = strings.TrimSpace(string(out))
	}

	gitRun(t, root, "clone", "-q", origin, clone)
	gitRun(t, clone, "config", "user.email", "test@example.com")
	gitRun(t, clone, "config", "user.name", "Test")
	return clone, tips
}

func headCommit(t *testing.T, dir string) string {
	t.Helper()
	out, err := exec.Command("git", "-C", dir, "rev-parse", "HEAD").Output()
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSpace(string(out))
}

func TestEnsurePolecatWorkBranch_BaseResolution(t *testing.T) {
	cases := []struct {
		name       string
		rigDefault string
		base       string
		wantBase   string
	}{
		{"rig base branch develop", "develop", "", "develop"},
		{"no rig config falls back to origin default", "", "", "main"},
		{"--base wins over rig config", "develop", "feature/stack", "feature/stack"},
		{"--base wins without rig config", "", "feature/stack", "feature/stack"},
		{"--base accepts an origin/ prefix", "", "origin/develop", "develop"},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			clone, tips := newRigClone(t, c.rigDefault)
			res, err := ensurePolecatWorkBranch(clone, "nux", "gt-abc", c.base)
			if err != nil {
				t.Fatalf("ensurePolecatWorkBranch: %v", err)
			}
			if res.Action != polecatBranchCreated {
				t.Fatalf("action = %q, want created", res.Action)
			}
			if got := headCommit(t, clone); got != tips[c.wantBase] {
				t.Errorf("new branch is at %s, want tip of %s (%s)", got, c.wantBase, tips[c.wantBase])
			}
		})
	}
}

